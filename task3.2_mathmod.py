# Importing the math module
import math

# Asking the user to enter a number
number = float(input("Enter a number: "))

# Calculating the square root of the number
square_root = math.sqrt(number)

# Calculating the natural logarithm (log base e)
log_value = math.log(number)

# Calculating the sine of the number (in radians)
sine_value = math.sin(number)

# Displaying the results
print("Square root:", square_root)
print("Logarithm:", log_value)
print("Sine:", sine_value)